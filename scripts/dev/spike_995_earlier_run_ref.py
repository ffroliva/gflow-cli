r"""Is an image from an EARLIER process, already in the project, referenced in place? (#995)

Cost: $0 — nothing is submitted. Navigation, DOM reads and the ``@`` picker only.
flow.google.com project required. Run AFTER a separate ``gflow image t2i --project P``
process produced the image (that generation is the "earlier invocation"; it spends one
image of daily quota, zero credits, and is not part of this script).

Question: #913's in-place path (``MigratedComposer.reference_existing`` ->
``await_existing_references`` -> ``attach_existing_references``) was live-verified only
for an image generated by the SAME process a moment earlier. #995 / PR #996 infer that an
image generated by an EARLIER process in the same project behaves identically (same grid
tile, same ``/asb/<token>`` identity, same picker). This probe drives the production
methods directly, in a fresh process, with the ref shaped exactly as the PR's CLI path
would shape it (catalog ``display_name``, ``in_project=True``), and stops before submit.

Arms:
  Q0 catalog: the earlier run's row records ``flow_project_id == P`` and a caption.
  Q1 positive: ``reference_existing`` with the real uuid + catalog caption.
  Q2 stale uuid: a random uuid carrying the REAL image's caption (a stale/wrong row).
  Q3 wrong caption: the real uuid with a caption Flow never wrote.
  (Q2/Q3 run with ``EXISTING_REF_WAIT_S`` lowered to 15 s so the reload loop is short.)

Pre-registered reading (written before the first run, 2026-10-19):

  Q0 true                 -> the PR's routing hint has data to act on for this use case.
  Q0 false (no project or no caption in the row) -> the PR changes nothing for this row;
                            #995's precondition does not hold on a gflow-written row.
  Q1 returns (uuid,) and read_chips shows exactly 1 chip of reference_type "media"
      -> an earlier-process image IS found in this page's grid and attached by token
         identity; the #913 path is not run-scoped. (Whether the SUBMIT carries the id is
         a separate question answered only by a real submit — see the spike doc's A/B.)
  Q1 raises ReferenceNotFoundError "not in this project's grid"
      -> the grid does not list older images (paging/virtualisation?): the PR's inference
         is FALSE as built; record grid size.
  Q1 raises "did not attach ... picker option(s)" -> caption search does not surface an
      older image, or its /asb token differs from the grid's: inference FALSE.
  Q2 raises ReferenceNotFoundError and leaves 0 chips -> a stale row fails loud (exit 32)
      and attaches nothing. Q2 returning, or leaving a chip -> PR's safety claim is FALSE.
  Q3 raises ReferenceNotFoundError and leaves 0 chips -> a wrong caption fails loud.
  A single run settles Q1 for this project only; it does not measure a project with
  more images than one page of the grid.

    uv run python scripts/dev/spike_995_earlier_run_ref.py --profile ffroliva \
        --project <uuid> --media <uuid>
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
import uuid
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))

from gflow_cli.api.image import Aspect, GenerateImageRequest, ImageRef, Model  # noqa: E402
from gflow_cli.api.transports import _mc_mention, migrated_composer as mc  # noqa: E402
from gflow_cli.config import get_settings  # noqa: E402
from gflow_cli.data.repository import DataRepository  # noqa: E402
from gflow_cli.data.store import DataStore  # noqa: E402
from gflow_cli.errors import ReferenceNotFoundError  # noqa: E402

from _spike_common import build_client, default_out_path, resolve_profile_dir, step  # noqa: E402, isort: skip


def _catalog_row(profile: str, media: str) -> dict[str, Any]:
    with DataStore.open(get_settings().resolved_db_path()) as store:
        asset = DataRepository(store).get_asset_by_flow_media_id(profile, media)
    if asset is None:
        return {"found": False}
    return {
        "found": True,
        "kind": str(asset.kind),
        "flow_project_id": asset.flow_project_id,
        "display_name": asset.metadata_json.get("display_name"),
    }


async def _arm(
    composer: mc.MigratedComposer, page: Any, project: str, ref: ImageRef
) -> dict[str, Any]:
    grid_calls = 0
    original = composer.await_existing_references

    async def counted(p: Any, refs: tuple[ImageRef, ...]) -> dict[str, str]:
        nonlocal grid_calls
        grid_calls += 1
        return await original(p, refs)

    composer.await_existing_references = counted  # type: ignore[method-assign]
    req = GenerateImageRequest(
        prompt="spike 995 probe (never submitted)",
        aspect=Aspect.from_cli("1:1"),
        model=Model.from_cli("nano2"),
        refs=(ref,),
    )
    token = await page.evaluate(mc._GRID_TOKEN_JS, ref.name)  # noqa: SLF001
    result: dict[str, Any] = {"grid_token": str(token or "")}
    try:
        ids = await composer.reference_existing(page, project, req)
        result.update(ok=True, ids=list(ids))
    except ReferenceNotFoundError as exc:
        result.update(ok=False, error=str(exc.detail)[:300])
    finally:
        composer.await_existing_references = original  # type: ignore[method-assign]
    result["grid_attempts"] = grid_calls
    result["chips"] = await composer.read_chips(page)
    await composer.clear_composer(page)
    result["chips_after_clear"] = len(await composer.read_chips(page))
    return result


async def main(profile: str, project: str, media: str) -> int:
    findings: dict[str, Any] = {"project": project, "media": media}
    out = default_out_path("spike_995_earlier_run_ref")

    def save() -> None:
        out.write_text(json.dumps(findings, indent=2, default=str), encoding="utf-8")

    row = _catalog_row(profile, media)
    findings["q0"] = row
    findings["q0_ok"] = (
        bool(row.get("found"))
        and row.get("flow_project_id") == project
        and bool(row.get("display_name"))
    )
    step("Q0", json.dumps(findings["q0"]))
    save()
    caption = str(row.get("display_name") or "")

    async with build_client(resolve_profile_dir(profile)) as client:
        ctx = client._context  # noqa: SLF001 - spike reads the live context
        assert ctx is not None
        page = ctx.pages[0] if ctx.pages else await ctx.new_page()
        composer = mc.MigratedComposer()
        findings["editor"] = await composer.ensure_editor(page, project)
        findings["grid_tiles"] = await page.evaluate(
            "() => document.querySelectorAll('img[data-media-id]').length"
        )
        step("editor", f"{findings['editor']} tiles={findings['grid_tiles']}")

        findings["q1"] = await _arm(
            composer, page, project, ImageRef(media, display_name=caption, in_project=True)
        )
        step("Q1", json.dumps(findings["q1"]))
        save()

        _mc_mention.EXISTING_REF_WAIT_S = 15.0
        findings["q2"] = await _arm(
            composer,
            page,
            project,
            ImageRef(str(uuid.uuid4()), display_name=caption, in_project=True),
        )
        step("Q2", json.dumps(findings["q2"]))
        save()
        findings["q3"] = await _arm(
            composer,
            page,
            project,
            ImageRef(media, display_name="zq spike nine nine five nothing", in_project=True),
        )
        step("Q3", json.dumps(findings["q3"]))
        save()
    step("wrote", str(out))
    return 0


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--profile", required=True)
    ap.add_argument("--project", required=True)
    ap.add_argument("--media", required=True)
    a = ap.parse_args()
    raise SystemExit(asyncio.run(main(a.profile, a.project, a.media)))
