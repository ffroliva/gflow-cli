"""Live E2E for the direct_http image transport (T1.6, T2.3, T2.4).

A plain text-to-image run on ``GFLOW_CLI_TRANSPORT=direct_http`` is generated by one
direct ``ogiZ0b`` POST and recorded with ``metadata_json.transport = "direct_http"``; two
16:9 images come from one direct POST; a model with no measured wire name is routed to the
UI transport before any POST and still generates. All image runs: daily quota, zero credits.

Opt in with:
    GFLOW_CLI_E2E_PROFILE=<profile-name> uv run pytest -m e2e_image -v \\
        tests/e2e/test_direct_image_e2e.py
"""

from __future__ import annotations

import json
import sqlite3
import subprocess
import sys
from typing import TYPE_CHECKING

import pytest

from tests.e2e._redacted_env import RedactedEnv

if TYPE_CHECKING:
    from pathlib import Path

pytestmark = [pytest.mark.e2e, pytest.mark.e2e_image]

_JPEG_OR_PNG = (b"\xff\xd8\xff", b"\x89PNG\r\n\x1a\n")


def _t2i(env: RedactedEnv, target: Path, *extra: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [
            sys.executable,
            "-m",
            "gflow_cli",
            "image",
            "t2i",
            "a paper boat on a pond",
            "--out-file",
            str(target),
            *extra,
        ],
        capture_output=True,
        text=True,
        check=False,
        env=env | {"GFLOW_CLI_TRANSPORT": "direct_http"},
    )


def _image_transports(env: RedactedEnv) -> list[str | None]:
    with sqlite3.connect(env["GFLOW_CLI_DB_PATH"]) as db:
        rows = db.execute("SELECT metadata_json FROM assets WHERE kind = 'image'").fetchall()
    return [json.loads(row[0] or "{}").get("transport") for row in rows]


def _saved(target: Path) -> Path:
    found = sorted(target.parent.glob(f"{target.stem}.*"))
    assert len(found) == 1, f"expected one file for {target}, found {found}"
    assert found[0].read_bytes().startswith(_JPEG_OR_PNG), f"{found[0]} is not an image"
    return found[0]


def test_plain_t2i_is_generated_by_the_direct_transport(
    e2e_env: RedactedEnv, tmp_path: Path
) -> None:
    proc = _t2i(e2e_env, tmp_path / "direct.jpg")
    assert proc.returncode == 0, f"gflow image t2i failed (exit {proc.returncode})"
    _saved(tmp_path / "direct.jpg")
    assert _image_transports(e2e_env) == ["direct_http"]


def test_two_landscape_images_come_from_one_direct_post(
    e2e_env: RedactedEnv, tmp_path: Path
) -> None:
    proc = _t2i(e2e_env, tmp_path / "wide.jpg", "--aspect", "16:9", "-n", "2")
    assert proc.returncode == 0, f"gflow image t2i failed (exit {proc.returncode})"
    files = sorted(p for p in tmp_path.iterdir() if p.name.startswith("wide"))
    assert len(files) == 2, files
    assert all(p.read_bytes().startswith(_JPEG_OR_PNG) for p in files)
    assert _image_transports(e2e_env) == ["direct_http", "direct_http"]


def test_a_model_with_no_measured_wire_name_routes_to_the_ui_transport(
    e2e_env: RedactedEnv, tmp_path: Path
) -> None:
    proc = _t2i(e2e_env, tmp_path / "pro.jpg", "--model", "nano-pro")
    assert proc.returncode == 0, f"gflow image t2i failed (exit {proc.returncode})"
    _saved(tmp_path / "pro.jpg")
    assert _image_transports(e2e_env) == [None]


def test_an_in_project_reference_is_generated_by_the_direct_transport(
    e2e_env: RedactedEnv, tmp_path: Path
) -> None:
    """T2.1: an i2i whose --ref is an image this project already holds goes direct."""
    first = _t2i(e2e_env, tmp_path / "source.jpg")
    assert first.returncode == 0, f"gflow image t2i failed (exit {first.returncode})"
    with sqlite3.connect(e2e_env["GFLOW_CLI_DB_PATH"]) as db:
        media_id, project_id = db.execute(
            "SELECT flow_media_id, flow_project_id FROM assets WHERE kind = 'image'"
        ).fetchone()
    proc = subprocess.run(
        [
            sys.executable,
            "-m",
            "gflow_cli",
            "image",
            "i2i",
            "the same scene at night",
            "--ref",
            media_id,
            "--project",
            project_id,
            "--out-file",
            str(tmp_path / "night.jpg"),
        ],
        capture_output=True,
        text=True,
        check=False,
        env=e2e_env | {"GFLOW_CLI_TRANSPORT": "direct_http"},
    )
    assert proc.returncode == 0, f"gflow image i2i failed (exit {proc.returncode})"
    _saved(tmp_path / "night.jpg")
    assert _image_transports(e2e_env) == ["direct_http", "direct_http"]
